package wgconf

import (
	"fmt"
	"strings"
)

// PeerSpec — данные для нового блока [Peer]. Приватного ключа здесь нет
// сознательно: серверу он не нужен и в серверный конфиг не попадает.
type PeerSpec struct {
	Name         string
	PublicKey    string
	PresharedKey string
	AllowedIPs   string
}

// validate проверяет поля PeerSpec перед тем, как они попадут в текст
// конфига. requirePSK различает два пути вызова (находка финального ревью,
// I1):
//   - AppendPeer (true) — панель создаёт блок сама и PSK для него генерирует
//     всегда; пустой PresharedKey здесь — не легитимный случай, а баг
//     вызывающего кода, и обязан отклоняться так же строго, как раньше.
//   - ReplacePeerBlock (false) — блок может принадлежать пиру, заведённому
//     руками до установки панели (на боевом сервере такие есть — см.
//     комментарии в internal/issuer/service.go), а у таких пиров
//     PresharedKey часто нет вовсе. Пустой PresharedKey здесь значит "у
//     пира его нет", а не "забыли передать": rewritePeerBlock ниже не
//     печатает строку PresharedKey, когда p.PresharedKey == "". Прежняя
//     редакция отклоняла такую замену безусловно — не просто лишней
//     строгостью: спека 3.1 прямо обещает, что таких пиров можно
//     переименовывать, а отказ уходил обычным fmt.Errorf, не
//     issuer.ErrInvalidInput, то есть оператор получал 500 «внутренняя
//     ошибка» вместо причины.
func (p PeerSpec) validate(requirePSK bool) error {
	required := map[string]string{"PublicKey": p.PublicKey, "AllowedIPs": p.AllowedIPs}
	if requirePSK {
		required["PresharedKey"] = p.PresharedKey
	}
	for name, v := range required {
		if v == "" {
			return fmt.Errorf("пустое поле %s", name)
		}
	}
	// Любой перевод строки или заголовок секции в данных — попытка инъекции
	// в конфиг. Отказ, а не экранирование: экранировать тут нечего.
	for name, v := range map[string]string{
		"Name": p.Name, "PublicKey": p.PublicKey,
		"PresharedKey": p.PresharedKey, "AllowedIPs": p.AllowedIPs,
	} {
		if strings.ContainsAny(v, "\r\n") {
			return fmt.Errorf("поле %s содержит перевод строки", name)
		}
		if strings.Contains(v, "[") || strings.Contains(v, "]") {
			return fmt.Errorf("поле %s содержит скобки заголовка секции", name)
		}
	}
	// Пробелы по краям PublicKey/PresharedKey/AllowedIPs отклоняются, а не
	// обрезаются молча: Get() при чтении конфига уже возвращает значения
	// после TrimSpace, поэтому нетронутое поле с хвостовым пробелом не
	// совпадёт при сравнении в FindPeer с тем же ключом без пробела —
	// проверка на дубликат в AppendPeer тихо пропустится, и в конфиге
	// окажутся два блока [Peer] с одним публичным ключом. Отказ честнее
	// тихого исправления: пробел на краю ключа — это, скорее всего,
	// опечатка при вставке, и её стоит показать пользователю, а не скрыть.
	for name, v := range map[string]string{
		"PublicKey": p.PublicKey, "PresharedKey": p.PresharedKey, "AllowedIPs": p.AllowedIPs,
	} {
		if strings.TrimSpace(v) != v {
			return fmt.Errorf("поле %s содержит пробелы по краям", name)
		}
	}
	return nil
}

// RenderPeerBlock собирает текст блока [Peer], завершающийся переводом строки.
// Имя пира пишется комментарием ВНУТРИ блока, чтобы удаление уносило его с собой.
func RenderPeerBlock(p PeerSpec, eol string) string {
	var b strings.Builder
	b.WriteString("[Peer]" + eol)
	if p.Name != "" {
		b.WriteString("# awg3panel: " + p.Name + eol)
	}
	b.WriteString("PublicKey = " + p.PublicKey + eol)
	b.WriteString("PresharedKey = " + p.PresharedKey + eol)
	b.WriteString("AllowedIPs = " + p.AllowedIPs + eol)
	return b.String()
}

// FindPeer ищет секцию [Peer] по публичному ключу.
func FindPeer(c *Config, publicKey string) (*Section, bool) {
	for _, s := range c.Peers {
		if s.Get("PublicKey") == publicKey {
			return s, true
		}
	}
	return nil, false
}

// AppendPeer дописывает блок [Peer] в конец текста.
//
// Исходные байты не меняются никогда: результат всегда начинается с исходного
// текста. Если файл не заканчивался переводом строки, он добавляется — это
// дописывание, а не правка существующих байтов.
//
// Пустая строка-разделитель перед блоком дописывается ТОЛЬКО когда пиры в
// конфиге уже есть. Причина не косметическая (Размен 1 финального ревью):
// границы секции определяются началом следующего заголовка, поэтому в
// конфиге БЕЗ пиров Interface.EndByte равен концу файла — и любой байт,
// дописанный перед "[Peer]", попадает ВНУТРЬ секции [Interface], растягивая
// её. Applier.assertInterfaceUntouched на такой результат законно
// отказывает: незыблемое правило 2 («[Interface] копируется побайтово»)
// срабатывает верно, ошибка — здесь. А поскольку удаление ПОСЛЕДНЕГО пира
// проходит без возражений, панель без этой поправки умеет удалить всех
// пиров и уже не умеет добавить ни одного обратно — необратимое состояние
// за несколько нажатий. Когда пиры есть, Interface.EndByte указывает на
// первый "[Peer]" и от дописывания в конец не зависит вовсе.
//
// Единственный случай, который поправка не спасает и спасти не может:
// конфиг без пиров, НЕ оканчивающийся переводом строки. Там сам перевод
// строки (без него "[Peer]" приклеился бы к последнему параметру) попадает
// в ту же секцию и растягивает её, так что мутация будет честно отклонена
// правилом 2. Панель в такое состояние не приводит: RemovePeerByPublicKey
// режет по границе секции, а она начинается сразу после перевода строки,
// поэтому файл после удаления последнего пира всегда им и заканчивается.
func AppendPeer(text string, p PeerSpec) (string, error) {
	if err := p.validate(true); err != nil {
		return "", err
	}
	c, err := Parse(text)
	if err != nil {
		return "", fmt.Errorf("исходный конфиг не разбирается: %w", err)
	}
	if _, exists := FindPeer(c, p.PublicKey); exists {
		return "", fmt.Errorf("пир с таким публичным ключом уже есть в конфиге")
	}
	eol := EOL(text)
	out := text
	if !strings.HasSuffix(out, eol) {
		out += eol
	}
	if len(c.Peers) > 0 {
		out += eol
	}
	return out + RenderPeerBlock(p, eol), nil
}

// RemovePeerByPublicKey вырезает ровно один блок [Peer] по байтовым границам
// секции. Всё, что вне вырезанного диапазона, остаётся теми же байтами.
//
// Вместе с блоком уносится разделительная пустая строка, которую дописал
// AppendPeer, — но ТОЛЬКО когда она заведомо принадлежит другому блоку [Peer]
// (см. separatorStart). Без этого конфиг не стабилен на круговом обходе:
// граница секции проходит по началу СЛЕДУЮЩЕГО заголовка, поэтому пустая
// строка перед "[Peer]" принадлежит ПРЕДЫДУЩЕЙ секции и в вырезаемый диапазон
// не попадает. Измерено на полигоне: файл в 1073 байта после цикла
// add → disable → enable → delete вернулся к исходному составу пиров, но стал
// 1075 байт с тремя "\n" на конце. Байт за цикл, без верхней границы; awg
// пустые строки игнорирует, так что рост молчалив.
func RemovePeerByPublicKey(text, publicKey string) (string, error) {
	c, err := Parse(text)
	if err != nil {
		return "", fmt.Errorf("исходный конфиг не разбирается: %w", err)
	}
	sec, ok := FindPeer(c, publicKey)
	if !ok {
		return "", fmt.Errorf("пир с публичным ключом не найден в конфиге")
	}
	return text[:separatorStart(text, c, sec)] + text[sec.EndByte:], nil
}

// separatorStart возвращает начало вырезаемого диапазона: обычно это
// sec.StartByte, но если перед блоком стоит разделительная пустая строка,
// принадлежащая ДРУГОМУ блоку [Peer], — на один перевод строки левее.
//
// Три условия, и каждое обязательно:
//
//  1. Удаляемый блок — последний в файле (sec.EndByte == len(text)). Только
//     тогда разделитель осиротеет: если за блоком есть следующая секция,
//     разделитель ПЕРЕД блоком остаётся законным разделителем между соседями,
//     а тот, что стоял ПОСЛЕ, и так входит в вырезаемый диапазон.
//
//  2. Байты непосредственно перед блоком принадлежат секции [Peer], а не
//     [Interface]. Это рубеж незыблемого правила 2, и ослабить его нельзя:
//     когда удаляемый пир ПЕРВЫЙ, пустая строка перед ним лежит ВНУТРИ границ
//     [Interface] (её EndByte — начало первого "[Peer]"), и уборка изменила бы
//     байты секции, которую менять запрещено. Applier.assertInterfaceUntouched
//     на такой результат законно откажет — то есть наивная уборка не просто
//     нарушила бы правило, а сломала бы удаление единственного пира вовсе.
//     Роста при этом не возникает: в конфиг БЕЗ пиров AppendPeer разделитель
//     не дописывает (см. его комментарий), так что цикл сходится и здесь.
//
//  3. Перед блоком действительно пустая строка (два перевода строки подряд),
//     а не просто конец предыдущей строки. Иначе шаг влево съел бы перевод
//     строки, завершающий последний параметр предыдущего пира, и склеил бы
//     его со следующим заголовком.
//
// Убирается РОВНО один перевод строки — точный обратный ход к тому, что
// дописывает AppendPeer. Уже накопленные ранее пустые строки не трогаются
// намеренно: это чужие байты (оператор вправе форматировать файл сам), а для
// прекращения роста достаточно точной обратимости — цикл add/remove сходится
// в неподвижную точку с первого же шага.
func separatorStart(text string, c *Config, sec *Section) int {
	if sec.EndByte != len(text) {
		return sec.StartByte
	}
	owner := sectionEndingAt(c, sec.StartByte)
	if owner == nil || owner == c.Interface {
		return sec.StartByte
	}
	eol := EOL(text)
	if !strings.HasSuffix(text[:sec.StartByte], eol+eol) {
		return sec.StartByte
	}
	return sec.StartByte - len(eol)
}

// sectionEndingAt возвращает секцию, которой принадлежат байты, лежащие
// непосредственно перед позицией pos, либо nil, если pos — начало файла.
// Сравнение по EndByte, а не по порядку в c.Peers: порядок секций в файле
// задаётся байтами, а [Interface] не обязана быть первой.
func sectionEndingAt(c *Config, pos int) *Section {
	if c.Interface != nil && c.Interface.EndByte == pos {
		return c.Interface
	}
	for _, p := range c.Peers {
		if p.EndByte == pos {
			return p
		}
	}
	return nil
}

// ReplacePeerBlock заменяет блок [Peer] с публичным ключом publicKey,
// СОХРАНЯЯ все его строки, которых нет в p. Всё, что вне байтовых границ
// этого блока, остаётся теми же байтами — включая [Interface], соседние
// [Peer] и пустые строки между ними.
//
// В ОТЛИЧИЕ от прежней редакции (находка финального ревью, I1) блок больше не
// собирается заново из четырёх полей p через RenderPeerBlock — это стирало
// всё, чего нет в PeerSpec: PersistentKeepalive, собственные комментарии
// оператора и любые другие параметры, дописанные вручную. На боевом сервере
// этой панели есть пиры, заведённые руками до её установки (см. комментарии
// в internal/issuer/service.go), и такие строки у них — обычное дело.
// rewritePeerBlock ниже переписывает РОВНО четыре вещи — комментарий
// "# awg3panel:", PublicKey, PresharedKey, AllowedIPs, — а все прочие строки
// блока копирует байт в байт и в исходном порядке.
//
// Разделительные пустые строки по-прежнему не трогаются: блок не исчезает, а
// замещается, поэтому разделителю не грозит осиротеть, и обратимость
// держится сама собой — замена блока на идентичный даёт тот же файл байт в
// байт, ЕСЛИ файл уже оканчивался переводом строки (иначе переименование
// пира растило бы файл при каждом нажатии, как это было с AppendPeer).
// Раньше это обеспечивала отдельная функция sectionTrailer (искала "хвост"
// после последней строки с параметром); построчная перезапись переносит эти
// байты как есть вместе со всем остальным, что не входит в управляемые поля,
// так что отдельная функция для этого больше не нужна.
//
// ОГОВОРКА к байт-в-байт гарантии (соседний пункт повторного финального
// ревью): если файл НЕ оканчивается переводом строки, а последняя строка
// целевого блока — управляемое поле (PublicKey/PresharedKey/AllowedIPs),
// синтезированная замена этой строки ("Key = Value" + eol в rewritePeerBlock)
// всегда дописывает перевод строки, которого в исходнике не было, — файл
// растёт на 1 байт при ПЕРВОЙ такой замене. Это сознательно не устранено:
// рост односторонний и самостабилизируется (после первой замены файл
// оканчивается переводом строки, и дальнейшие замены его больше не трогают)
// — тот же эффект, что AppendPeer уже производит для конфига без пиров (см.
// её доккомментарий), а не находка 1 живого выката (там рост был
// неограниченным, по байту за КАЖДЫЙ цикл). Граница закреплена тестом
// TestReplacePeerBlockOnFileWithoutTrailingNewlineGrowsOnceThenStabilizes.
//
// ВНУТРИ блока (а не на его последней строке) байт-в-байт держится
// безусловно, независимо от завершающего перевода строки файла: строка,
// которой не было (PresharedKey/AllowedIPs), дописывается через terminateLast
// — она гарантирует разделитель ПЕРЕД новой строкой, если последняя
// перенесённая строка блока лишена собственного (регресс повторного
// финального ревью: без этого дописанная строка приклеивалась к
// комментарию оператора на одну физическую строку, и для PresharedKey это
// был молчаливый, а не шумный отказ — см. комментарий у terminateLast).
//
// Смена PublicKey допускается — это ротация ключей пира. Проверка на дубликат
// обязательна: новый ключ не должен совпасть с ключом ДРУГОГО блока, иначе в
// конфиге окажутся два [Peer] с одним публичным ключом, и awg молча оставит
// один из них.
func ReplacePeerBlock(text, publicKey string, p PeerSpec) (string, error) {
	// requirePSK=false: см. комментарий у PeerSpec.validate. Пустой
	// PresharedKey на пути замены — легитимный случай (у пира его нет от
	// природы блока, заведённого руками), а не ошибка ввода.
	if err := p.validate(false); err != nil {
		return "", err
	}
	c, err := Parse(text)
	if err != nil {
		return "", fmt.Errorf("исходный конфиг не разбирается: %w", err)
	}
	sec, ok := FindPeer(c, publicKey)
	if !ok {
		return "", fmt.Errorf("пир с публичным ключом не найден в конфиге")
	}
	if p.PublicKey != publicKey {
		if other, exists := FindPeer(c, p.PublicKey); exists && other != sec {
			return "", fmt.Errorf("пир с новым публичным ключом уже есть в конфиге")
		}
	}
	eol := EOL(text)
	newBlock := rewritePeerBlock(sec.Bytes(text), eol, p)
	return text[:sec.StartByte] + newBlock + text[sec.EndByte:], nil
}

// paramKey возвращает имя параметра строки вида "Ключ = значение" — тем же
// способом, что и Parse (TrimSpace всего слева от первого "="). Это НЕ
// keyNameOnly из parse.go: та эвристика нарочно занижает чувствительность,
// чтобы не напечатать секрет в сообщении об ошибке, а здесь нужно опознать
// РЕАЛЬНЫЙ ключ параметра, каким бы длинным он ни был — иначе, например,
// строка PrivateKey (43+ символов) молча провалилась бы в "прочие" и не
// распозналась бы как параметр вовсе, хотя это не тот случай, который здесь
// вообще встречается (блок [Peer] приватных ключей не хранит), но правило
// обязано быть общим, а не подогнанным под три конкретных имени.
// trimmedContent — уже избавленная от переводов строки строка без пробелов
// по краям. Пустой результат означает "это не строка параметра" (пустая
// строка, комментарий, строка без "=").
func paramKey(trimmedContent string) string {
	if trimmedContent == "" || strings.HasPrefix(trimmedContent, "#") || strings.HasPrefix(trimmedContent, ";") {
		return ""
	}
	key, _, ok := strings.Cut(trimmedContent, "=")
	if !ok {
		return ""
	}
	return strings.TrimSpace(key)
}

// rewritePeerBlock переписывает блок [Peer] МИНИМАЛЬНО. block — точные байты
// блока (см. Section.Bytes), eol — перевод строки файла для СИНТЕЗИРУЕМЫХ
// строк. Резка block на строки идёт по голому "\n" (как в Parse), а не по
// eol целиком: иначе CRLF-строка блока (заканчивающаяся "\r\n") потеряла бы
// свой "\r" не в том месте.
//
// Заголовок "[Peer]" копируется как есть — управляемым полем не является.
// Дальше каждая строка либо распознаётся как одна из четырёх управляемых
// панелью (комментарий вида "# awg3panel: <имя>", PublicKey, PresharedKey,
// AllowedIPs) и переписывается значением из p, либо — если это не одна из
// них — копируется байт в байт на прежнем месте: PersistentKeepalive,
// комментарий оператора, пустая строка-разделитель, что угодно ещё.
//
// Управляемая строка, которой в блоке не было, дописывается: комментарий с
// именем — сразу после заголовка (то же место, где его ставит RenderPeerBlock
// для новых блоков; nameFromComment в issuer/service.go ищет его по всему
// блоку, а не по позиции, так что порядок здесь — вопрос читаемости, а не
// корректности), PresharedKey и AllowedIPs, если их не было, — в конец,
// следом за перенесёнными строками (порядок внутри секции [Peer] сам по себе
// не имеет значения ни для awg, ни для Parse). Перед каждым таким
// дописыванием в конец — terminateLast: последняя перенесённая строка блока
// могла быть скопирована байт в байт без собственного перевода строки
// (последняя строка блока, последнего в файле без завершающего перевода
// строки), и без явного разделителя новая строка приклеилась бы к ней.
//
// Пустой p.Name — строка комментария не пишется вовсе (убирается, если была;
// не добавляется, если не было) — то же правило, что действует в
// RenderPeerBlock. Пустой p.PresharedKey — строка PresharedKey не пишется: у
// пира её нет (см. комментарий у PeerSpec.validate, находка финального
// ревью I1).
func rewritePeerBlock(block, eol string, p PeerSpec) string {
	lines := strings.SplitAfter(block, "\n")
	if len(lines) == 0 {
		return block // защитная ветка: пустой блок — переписывать нечего
	}
	header := lines[0] // "[Peer]" + перевод строки
	nameLine := func() string { return "# awg3panel: " + p.Name + eol }

	var out []string
	sawName, sawPub, sawPSK, sawIPs := false, false, false, false
	for _, line := range lines[1:] {
		content := strings.TrimSpace(strings.TrimSuffix(strings.TrimSuffix(line, "\n"), "\r"))
		key := paramKey(content)
		switch {
		case strings.HasPrefix(content, "# awg3panel:"):
			sawName = true
			if p.Name != "" {
				out = append(out, nameLine())
			}
		case strings.EqualFold(key, "PublicKey"):
			sawPub = true
			out = append(out, "PublicKey = "+p.PublicKey+eol)
		case strings.EqualFold(key, "PresharedKey"):
			sawPSK = true
			if p.PresharedKey != "" {
				out = append(out, "PresharedKey = "+p.PresharedKey+eol)
			}
		case strings.EqualFold(key, "AllowedIPs"):
			sawIPs = true
			out = append(out, "AllowedIPs = "+p.AllowedIPs+eol)
		default:
			out = append(out, line) // чужая строка — переносится как есть
		}
	}

	if !sawPub {
		// Практически недостижимо: ReplacePeerBlock находит sec через
		// FindPeer, который сравнивает Get("PublicKey") с publicKey, — а без
		// строки PublicKey в блоке взять его неоткуда. Строка на всякий
		// случай дописывается, а не теряется молча, если этот инвариант
		// когда-нибудь нарушится выше по стеку.
		out = append([]string{"PublicKey = " + p.PublicKey + eol}, out...)
	}
	if !sawPSK && p.PresharedKey != "" {
		out = terminateLast(out, eol)
		out = append(out, "PresharedKey = "+p.PresharedKey+eol)
	}
	if !sawIPs {
		out = terminateLast(out, eol)
		out = append(out, "AllowedIPs = "+p.AllowedIPs+eol)
	}
	if !sawName && p.Name != "" {
		out = append([]string{nameLine()}, out...)
	}

	return header + strings.Join(out, "")
}

// terminateLast гарантирует, что последняя НЕПУСТАЯ строка out (если такая
// есть) оканчивается переводом строки, — вызывается ПЕРЕД тем, как в конец
// out дописывается управляемая строка, которой не было в исходном блоке
// (PresharedKey/AllowedIPs; см. их вызовы в rewritePeerBlock). Это НЕ
// косметика (регресс повторного финального ревью): последний элемент out
// мог быть скопирован байт в байт из ПОСЛЕДНЕЙ строки блока (ветка default
// цикла выше), а она лишена перевода строки РОВНО тогда, когда блок —
// последний в файле, а сам файл не оканчивается переводом строки
// (strings.SplitAfter оставляет ровно один такой "хвост" без разделителя —
// см. её вызов в начале rewritePeerBlock). Без явного добавления eol здесь
// дописываемая строка приклеилась бы к предыдущей на одну физическую строку
// текста: "# комментарий" + "PresharedKey = X\n" → "# комментарийPresharedKey = X\n".
//
// Для PresharedKey это не шумный отказ, а МОЛЧАЛИВЫЙ: если приклеенная
// строка начинается с "#" (комментарий оператора, конец блока пира,
// заведённого руками, — ровно тот пир, ради которого правилась находка I1),
// склейка остаётся ОДНИМ ВАЛИДНЫМ комментарием при разборе — Parse доволен,
// assertInterfaceUntouched доволен, syncconf комментарии игнорирует, а
// checkPostcondition для пира из exp.Added (Applier.Apply, при добавлении/
// ротации) сверяет только факт появления пира на устройстве и PresharedKey
// не проверяет вовсе (в отличие от пиров, уже бывших в снимке "до" мутации).
// Панель рапортует успех и отдаёт оператору клиентский конфиг С
// PresharedKey, которого на сервере НЕТ: клиент молча и навсегда не
// подключается, а причина не видна без ручного чтения awg3.conf.
//
// Пустые элементы out (хвост strings.SplitAfter, когда блок УЖЕ оканчивался
// переводом строки — тогда добавлять нечего) пропускаются: иначе проверка
// суффикса "" всегда была бы отрицательной, и eol дописывался бы туда, где
// текст и так уже корректно завершён предыдущим непустым элементом, — то
// есть внутрь [Peer] добавилась бы лишняя пустая строка при каждой замене.
func terminateLast(out []string, eol string) []string {
	for i := len(out) - 1; i >= 0; i-- {
		if out[i] == "" {
			continue
		}
		if !strings.HasSuffix(out[i], "\n") {
			out[i] += eol
		}
		return out
	}
	// Все элементы out пусты либо out пуст вовсе — переносить нечего:
	// дописываемая строка ляжет сразу после header, а он сам гарантированно
	// оканчивается переводом строки (см. комментарий у rewritePeerBlock).
	return out
}
