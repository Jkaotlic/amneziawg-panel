func runCLI(cmd string, args []string, svc *issuer.Service, out io.Writer) error {
	switch cmd {
	case "list":
		return listPeers(svc, out)

	case "add":
		if len(args) == 0 {
			return cliInputError{"укажите имя: awg3panel add <имя>"}
		}
		if err := refuseIfDaemonRunning(svc); err != nil {
			return err
		}
		issued, err := svc.Add(args[0])
		if err != nil {
			return err
		}
		// issued.Config содержит приватный ключ и PSK клиента — секрет не
		// слабее пароля из hashPasswordCmd (main.go), а сильнее: им
		// напрямую поднимается конкретный туннель. В отличие от пароля
		// здесь нет более безопасной альтернативы — печать готового
		// клиентского конфига и есть единственный смысл команды add,
		// другого способа получить его из CLI не предусмотрено. Но цену
		// стоит понимать явно, как и там: строка останется в скроллбэке
		// терминала, а если вызов когда-нибудь обернут скриптом,
		// перенаправляющим вывод в файл или journal (systemd-таймер,
		// CI) — то и там (fix round 1, minor 5).
		fmt.Fprintf(out, "# пир %s, id %s, адрес %s\n%s",
			issued.Name, issued.ID, issued.Address, issued.Config)
		return nil

	case "rm", "disable", "enable":
		if len(args) == 0 {
			return cliInputError{fmt.Sprintf("укажите id: awg3panel %s <id>", cmd)}
		}
		if err := refuseIfDaemonRunning(svc); err != nil {
			return err
		}
		var err error
		switch cmd {
		case "rm":
			err = svc.Remove(args[0])
		case "disable":
			err = svc.Disable(args[0])
		case "enable":
			err = svc.Enable(args[0])
		}
		if err != nil {
			return err
		}
		fmt.Fprintf(out, "готово: %s %s\n", cmd, args[0])
		return nil
	}
	return cliInputError{fmt.Sprintf("неизвестная команда %q", cmd)}
}

// daemonCheckTimeout — сколько refuseIfDaemonRunning ждёт ответа, прежде чем
// решить, что cfg.Listen никто не слушает. Демон на СВОЁМ ЖЕ туннельном
// адресе (том самом, на котором работает и сам этот хост) отвечает на SYN
// почти мгновенно — большой таймаут только продлевал бы каждую мутацию
// впустую в обычном случае, когда демон не запущен: CLI и существует как
// инструмент именно на этот случай (см. refuseIfDaemonRunning).
const daemonCheckTimeout = 300 * time.Millisecond

// daemonIsListening проверяет КЛИЕНТСКИМ подключением (net.DialTimeout), а
// не попыткой самой занять адрес (net.Listen). Разница принципиальна: адрес
// cfg.Listen — это адрес туннельного интерфейса awg3, и net.Listen на нём
// требует, чтобы этот адрес был реально назначен какому-то локальному
// интерфейсу. В тестах (runtime.Fake, без единого настоящего интерфейса
// awg3) и на машине разработки такого интерфейса нет — net.Listen проваливался
// бы там ВСЕГДА, но не потому, что порт занят демоном, а потому что адреса
// не существует локально вовсе, и ложно блокировал бы каждую мутацию даже
// там, где демону взяться неоткуда. net.DialTimeout спрашивает именно то,
// что нужно — "отвечает ли кто-то на этом адресе" — и не имеет этой
// проблемы: недостижимый адрес просто не отвечает.
func daemonIsListening(addr string) bool {
	conn, err := net.DialTimeout("tcp", addr, daemonCheckTimeout)
	if err != nil {
		return false
	}
	conn.Close()
	return true
}

// refuseIfDaemonRunning — единственная защита CLI-мутаций от риска,
// названного в ревью Task 14: Service.mu (Task 13) сериализует мутации
// только ВНУТРИ одного процесса, а CLI-команда — это отдельный процесс со
// своим экземпляром Service и своим мьютексом. Два процесса, идущие по
// циклу «прочитать awg3.conf и peers.json → изменить → записать»
// одновременно, могут потерять запись друг друга или откатить чужую (см.
// подробный разбор в task-14-report.md).
//
// Модель, которую выражает эта проверка: панель — основной интерфейс,
// CLI-мутации — инструмент восстановления на случай, когда демон НЕ
// работает. Они не рассчитаны на одновременную работу, и проверка честно
// разводит их по этому принципу, а не притворяется, что мутации CLI и
// демона равноправны и просто синхронизированы.
//
// Это СОВЕТ, а не гарантия взаимного исключения: между этой проверкой и
// фактической мутацией остаётся окно, в которое демон теоретически успевает
// подняться, — здесь нет ни блокировки, ни рукопожатия с демоном, только
// однократный опрос адреса перед тем, как начать. Непойманное — честно, без
// приукрашивания (ровно такая переоценка защиты уже стоила Critical в Task
// 13 — не повторять):
//
//   - Одновременный старт: администратор запускает панель и вводит
//     CLI-команду практически синхронно — TOCTOU-окно между опросом и
//     Apply. Для одного администратора редкий случай, но не нулевой.
//   - Рассинхронизация адреса — не экзотика, а основной практический риск:
//     эта проверка бьёт по svc.ListenAddr(), то есть по cfg.Listen из
//     СВОЕГО -config, который CLI загрузил сам (main.go), а не спросила у
//     демона. Восстановительную команду запускают именно в нештатной
//     ситуации — с другим `-config`, либо когда `listen:` в config.yaml
//     уже поправили, а демон продолжает слушать старый адрес (перечитает
//     только на рестарте). В обоих случаях DialTimeout уходит на другой,
//     свободный адрес, проверка молча отвечает «никто не слушает», и
//     мутация выполняется, пока живой демон работает на прежнем — см.
//     TestRefuseIfDaemonRunningMissesAddressMismatch.
//   - Симметрично не защищает от двух параллельных CLI-мутаций — только от
//     пары «демон ↔ CLI», и то не при каждом расхождении конфигов.
//
// Настоящее закрытие риска (файловая блокировка, действующая между ЛЮБЫМИ
// процессами, включая демон) рассмотрено и сознательно отложено: код с
// платформенным ветвлением (flock на Linux и Windows — разные вызовы)
// нельзя полноценно проверить в том виде, в каком он поедет на боевой
// сервер, разрабатывая на Windows, а цена ошибки в самой блокировке — выше
// цены риска, который она закрывает, особенно непосредственно перед
// выкатом на живой туннель.
func refuseIfDaemonRunning(svc *issuer.Service) error {
	addr := svc.ListenAddr()
	if addr == "" || !daemonIsListening(addr) {
		return nil
	}
	// %w вставляет errDaemonRunning.Error() ("похоже, панель уже запущена")
	// как есть — обёртка НЕ повторяет эту фразу, а продолжает предложение
	// (fix round 1, minor 2: раньше здесь стояло "%w: похоже, панель уже
	// запущена и слушает..." — администратор видел фразу дважды подряд).
	return fmt.Errorf("%w и слушает %s — измените пира через веб-интерфейс, "+
		"либо сначала остановите демон (например, systemctl stop awg3panel) "+
		"и повторите команду",
		errDaemonRunning, addr)
}
